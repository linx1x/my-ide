#!/usr/bin/env node
/**
 * Interactive first-run setup for My IDE.
 * Collects: phone number and optional dashboard workdir.
 * Writes .env and creates data dirs.
 */
import { createInterface } from 'node:readline';
import type { Interface } from 'node:readline';
import { writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';

const _ENV_PATH = resolve(process.cwd(), '.env');
const DATA_DIR = process.env.DOCKER_DATA_DIR || process.cwd();

function ask(rl: Interface, question: string, defaultValue = ''): Promise<string> {
  const suffix = defaultValue ? ` [${defaultValue}]` : '';
  return new Promise<string>((resolve) => {
    rl.question(`${question}${suffix}: `, (answer) => {
      resolve((answer || defaultValue).trim());
    });
  });
}

export async function runSetup(options: { nonInteractive?: boolean } = {}): Promise<boolean> {
  const { nonInteractive = false } = options;

  if (nonInteractive) {
    console.log('\n⚠️  Non-interactive mode. For first-time setup, run:');
    console.log('   docker compose run --rm -it bridge');
    console.log('   (or: docker run -it --rm -v $(pwd)/data:/data my-ide)\n');
    return false;
  }

  console.log('\n╔══════════════════════════════════════════════════════╗');
  console.log('║   My IDE — First-Run Setup                    ║');
  console.log('╚══════════════════════════════════════════════════════╝\n');

  const rl = createInterface({ input: process.stdin, output: process.stdout });

  try {
    const phoneNumber = await ask(
      rl,
      'WhatsApp number (country code, no +)',
      process.env.ALLOWED_NUMBERS || ''
    );
    if (!phoneNumber) {
      console.log('\n❌ Phone number required for WhatsApp. Example: 33612345678');
      rl.close();
      return false;
    }

    const defaultWorkdir = process.env.DASHBOARD_WORKDIR || (process.env.DOCKER ? '/workspace' : process.cwd());
    const workdir = await ask(
      rl,
      'Dashboard working directory',
      defaultWorkdir
    );

    const enableDashboard = await ask(
      rl,
      'Enable web dashboard (IDE mode)? [1] Yes  [2] No',
      process.env.DOCKER ? '1' : '2'
    );
    const useDashboard = enableDashboard !== '2';

    const authStore = process.env.DOCKER ? `${DATA_DIR}/auth_store` : 'auth_store';
    const lines = [
      '# Generated by setup script',
      `DASHBOARD_WORKDIR=${workdir}`,
    ];
    lines.push(`ALLOWED_NUMBERS=${phoneNumber}`);
    lines.push(`AUTH_STORE_PATH=${authStore}`);
    if (useDashboard) {
      lines.push('DASHBOARD_ENABLED=1');
      lines.push(`DASHBOARD_SECRET=${randomBytes(32).toString('hex')}`);
    }
    const envContent = lines.join('\n') + '\n';

    const targetPath = resolve(DATA_DIR, '.env');
    const dir = resolve(targetPath, '..');
    if (!existsSync(dir)) {mkdirSync(dir, { recursive: true });}
    writeFileSync(targetPath, envContent, 'utf8');

    console.log('\n✓ Configuration saved to .env');
    console.log('\nWhatsApp: On first start, scan the QR code with:');
    console.log('  WhatsApp → Settings → Linked Devices → Link a Device');
    if (useDashboard) {
      console.log('\nDashboard: Web IDE on port 3847. Use WhatsApp OTP to log in.');
    }
    console.log('');
    rl.close();
    return true;
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.error('Setup error:', message);
    rl.close();
    return false;
  }
}

export function needsSetup(dataDir = DATA_DIR) {
  const envPath = resolve(dataDir, '.env');
  if (!existsSync(envPath)) {return true;}
  const content = readFileSync(envPath, 'utf8');
  const hasWhatsApp = /ALLOWED_NUMBERS=\s*\S+/.test(content);
  return !hasWhatsApp;
}

/**
 * Create .env in dataDir from process.env (for Docker without a terminal).
 * Requires ALLOWED_NUMBERS in the environment.
 * @returns true if .env was written, false if required vars are missing
 */
export function writeEnvFromEnvVars(dataDir = DATA_DIR) {
  const phone = (process.env.ALLOWED_NUMBERS || '').trim();
  if (!phone) {return false;}

  const workdir = process.env.DASHBOARD_WORKDIR || (process.env.DOCKER ? '/workspace' : process.cwd());
  const authStore = process.env.DOCKER ? `${dataDir}/auth_store` : 'auth_store';
  const dashboardSecret = process.env.DASHBOARD_SECRET || randomBytes(32).toString('hex');
  const lines = [
    '# Generated from environment (no terminal setup)',
    `DASHBOARD_WORKDIR=${workdir}`,
    `ALLOWED_NUMBERS=${phone}`,
    `AUTH_STORE_PATH=${authStore}`,
    'DASHBOARD_ENABLED=1',
    `DASHBOARD_SECRET=${dashboardSecret}`,
  ];
  const targetPath = resolve(dataDir, '.env');
  const dir = resolve(targetPath, '..');
  if (!existsSync(dir)) {mkdirSync(dir, { recursive: true });}
  writeFileSync(targetPath, lines.join('\n') + '\n', 'utf8');
  return true;
}

// Allow running standalone: node scripts/setup.js
if (process.argv[1]?.endsWith('setup.js')) {
  runSetup().then((ok) => process.exit(ok ? 0 : 1));
}
